const dictionaries: Record<Lang, Record<TKey, string>> = { en, sv }

type I18nContextValue = {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: TKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  // Swedish is the product's home market — default to it unless the visitor
  // has an explicit preference stored in localStorage ('ek-lang').
  const [lang, setLangState] = useState<Lang>('sv')

  useEffect(() => {
    const stored = window.localStorage.getItem('ek-lang')
    if (stored === 'sv' || stored === 'en') {
      // apply after hydration to avoid cascading renders (React lint rule)
      queueMicrotask(() => {
        setLangState(stored)
        document.documentElement.lang = stored
      })
    }
  }, [])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    window.localStorage.setItem('ek-lang', l)
    document.documentElement.lang = l
  }, [])

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replaceAll(`{${k}}`, String(v))
        }
      }
      return text
    },
    [lang],
  )

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
}

export function useLang(): I18nContextValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useLang must be used within I18nProvider')
  return ctx
}
